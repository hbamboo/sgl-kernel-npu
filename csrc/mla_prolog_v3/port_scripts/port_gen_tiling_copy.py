#!/usr/bin/env python3
"""Generate the GM->local tiling copy helper for MlaPrologV3.

The CANN direct-launch build does not provide GET_TILING_DATA_WITH_STRUCT (that
macro comes from the msopgen-generated kernel_tiling header), and an A5 struct
copy from a __gm__ pointer is rejected by the compiler, so the tiling data is
copied field by field.  Keep this generator in sync with
csrc/mla_prolog/op_kernel/mla_prolog_tiling_data.h.
"""
import io
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "csrc/mla_prolog/op_kernel/mla_prolog_tiling_data.h")
DST = os.path.join(ROOT, "csrc/mla_prolog_v3/op_kernel/mla_prolog_v3_tiling_copy.h")

text = io.open(SRC, encoding="utf-8").read()


def fields(struct_name):
    m = re.search(r"struct %s \{(.*?)\n\};" % struct_name, text, re.S)
    if m is None:
        raise SystemExit("struct %s not found" % struct_name)
    body = m.group(1)
    out = []
    for line in body.splitlines():
        line = line.split("//")[0].strip()
        if not line or ";" not in line:
            continue
        decl = line.split(";")[0]
        parts = decl.replace("*", " * ").split()
        name = parts[-1].strip()
        if not name or "(" in name or name.startswith("#"):
            continue
        out.append(name)
    return out


base = fields("MlaPrologBaseParams")
tpl = fields("MlaPrologTplArgs")

lines = []
lines.append("// Generated by .port_gen_tiling_copy.py -- do not edit by hand.")
lines.append("#ifndef MLA_PROLOG_V3_TILING_COPY_H")
lines.append("#define MLA_PROLOG_V3_TILING_COPY_H")
lines.append("")
lines.append('#include "mla_prolog_tiling_data.h"')
lines.append("")
lines.append("namespace optiling {")
lines.append("")
lines.append("// Copies the GM tiling blob into local memory field by field (A5 rejects a")
lines.append("// struct-by-value copy from a __gm__ pointer).")
lines.append("__aicore__ inline void CopyMlaPrologTilingDataFromGm(__gm__ uint8_t *tilingGmPtr,")
lines.append("                                                   MlaPrologTilingData &dst)")
lines.append("{")
lines.append("    const __gm__ MlaPrologTilingData *src =")
lines.append("        reinterpret_cast<const __gm__ MlaPrologTilingData *>(tilingGmPtr);")
lines.append("    const __gm__ MlaPrologBaseParams *sb = &src->baseParams;")
lines.append("    MlaPrologBaseParams *db = &dst.baseParams;")
for f in base:
    lines.append("    db->%s = sb->%s;" % (f, f))
lines.append("    const __gm__ MlaPrologTplArgs *st = &src->tplArgs;")
for f in tpl:
    lines.append("    dst.tplArgs.%s = st->%s;" % (f, f))
lines.append("    dst.tilingKey = src->tilingKey;")
lines.append("}")
lines.append("")
lines.append("} // namespace optiling")
lines.append("")
lines.append("#endif // MLA_PROLOG_V3_TILING_COPY_H")

io.open(DST, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("generated", DST, "base fields:", len(base), "tpl fields:", len(tpl))
